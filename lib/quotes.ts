export function getQuoteForToday(seedDate?: string): QuoteItem {
  const date = seedDate ? new Date(seedDate) : new Date();
  // Compute day of year
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = (date.getTime() - start.getTime()) + ((start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000);
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Pick quote deterministically based on day of year
  const index = Math.abs(dayOfYear) % ASCEND_QUOTES.length;
  return ASCEND_QUOTES[index];
}

export function getRandomQuote(): QuoteItem {
  const idx = Math.floor(Math.random() * ASCEND_QUOTES.length);
  return ASCEND_QUOTES[idx];
}
